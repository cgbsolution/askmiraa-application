/**
 * Turn the spot illustrations into react-native-svg drawings for the app.
 *
 *   npm run spots
 *
 * Reads the website's spots (website/src/components/illustrations/spots.tsx)
 * and the app's own (scripts/spots/extra.tsx), draws each to static SVG with
 * React, and writes:
 *
 *   src/components/spots/drawings.gen.tsx   one drawing per spot
 *   src/core/spotNames.ts                   the names, for code and tests
 *
 * Two things differ from the browser and are handled here:
 * - react-native-svg has no `paint-order`. The website's "cut" (an outline in
 *   the tile's colour painted under a shape's fill, so layers read like
 *   printed paper) is drawn as two shapes: the outline, then the fill.
 * - The tones are CSS variables on the web; here they are passed in (the
 *   artwork tones from theme/tokens.ts, and the tile colour for the cut).
 */

import { join } from 'node:path';

import { MOBILE, combinedSource, loadSpots, markup, spotKey, writeFile } from './lib.mjs';
import { TAGS, emit, parse } from './native.mjs';

const spots = loadSpots(combinedSource());
const entries = Object.entries(spots)
  .map(([exportName, component]) => ({ key: spotKey(exportName), exportName, nodes: parse(markup(component)) }))
  .sort((a, b) => a.key.localeCompare(b.key));

const seen = new Set();
for (const entry of entries) {
  if (seen.has(entry.key)) throw new Error(`Two spots are called ${entry.key}`);
  seen.add(entry.key);
}

const used = new Set();
const body = entries.map((entry) => {
  const lines = entry.nodes.flatMap((node) => emit(node, 4));
  for (const line of lines) for (const tag of Object.values(TAGS)) if (line.includes(`<${tag} `)) used.add(tag);
  return `/** ${entry.exportName} */\nconst ${entry.key} = (c: SpotInk) => (\n  <>\n${lines.join('\n')}\n  </>\n);`;
});

const header = `/**
 * GENERATED by scripts/spots/build.mjs — do not edit by hand.
 *
 * The spot illustrations, drawn for react-native-svg from the website's
 * website/src/components/illustrations/spots.tsx and the app's own
 * scripts/spots/extra.tsx. To change one, change it there and run
 * \`npm run spots\`. Shown through <Spot> and <SpotTile> (components/Spot.tsx).
 */

import type { ReactElement } from 'react';
import { ${[...used].sort().join(', ')} } from 'react-native-svg';

import type { SpotName } from '../../core/spotNames';

/** The artwork's tones, and the tile colour it sits on (for the cuts). */
export interface SpotInk {
  d: string;
  r: string;
  p: string;
  m: string;
  w: string;
  bg: string;
}
`;

const footer = `
export const SPOT_DRAWINGS: Record<SpotName, (c: SpotInk) => ReactElement> = {
${entries.map((entry) => `  ${entry.key},`).join('\n')}
};
`;

writeFile(join(MOBILE, 'src/components/spots/drawings.gen.tsx'), `${header}\n${body.join('\n\n')}\n${footer}`);

writeFile(
  join(MOBILE, 'src/core/spotNames.ts'),
  `/**
 * GENERATED by scripts/spots/build.mjs — do not edit by hand.
 *
 * Every spot illustration the app can draw (components/Spot.tsx). Plain
 * TypeScript so the catalogue and the tests can name them.
 */

export const SPOT_NAMES = [
${entries.map((entry) => `  '${entry.key}',`).join('\n')}
] as const;

export type SpotName = (typeof SPOT_NAMES)[number];
`,
);

console.log(`${entries.length} spots → src/components/spots/drawings.gen.tsx, src/core/spotNames.ts`);
